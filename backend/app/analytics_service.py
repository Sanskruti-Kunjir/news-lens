"""Analytics service: trending topics, keyword analysis, and prediction-history stats.

Data sources
------------
- ``artifacts/dataset_summary.json`` — pre-computed category counts, date
  ranges, and year-by-year breakdowns (generated by ``ml.explore_dataset``).
- ``data/processed/clean.csv`` — used for keyword extraction (sampled and
  cached for performance).
- SQLite ``prediction_history`` table — application usage analytics.
"""
from __future__ import annotations

import json
import logging
import sqlite3
from contextlib import closing
from pathlib import Path

import numpy as np
import pandas as pd
from sklearn.feature_extraction.text import TfidfVectorizer

log = logging.getLogger("newslens.analytics")


class AnalyticsService:
    """Provides dataset analytics, trending topics, and prediction-history
    statistics.  Expensive computations are cached."""

    def __init__(self, artifacts_dir: Path, dataset_path: Path):
        self._artifacts_dir = Path(artifacts_dir)
        self._dataset_path = Path(dataset_path)
        self._summary_cache: dict | None = None
        self._keyword_cache: dict = {}

    # ------------------------------------------------------------------ helpers
    def _load_summary(self) -> dict:
        if self._summary_cache is None:
            path = self._artifacts_dir / "dataset_summary.json"
            if path.exists():
                self._summary_cache = json.loads(path.read_text(encoding="utf-8"))
            else:
                self._summary_cache = {}
        return self._summary_cache

    # ------------------------------------------------------------------ categories
    def get_categories(self) -> dict:
        s = self._load_summary()
        counts = s.get("category_counts", {})
        total = s.get("total_records", sum(counts.values()))
        return {
            "total_records": total,
            "n_categories": len(counts),
            "categories": [
                {"category": c, "count": n, "percentage": round(n / max(total, 1) * 100, 2)}
                for c, n in sorted(counts.items(), key=lambda kv: -kv[1])
            ],
            "source": "Full cleaned dataset (historical, not live news)",
        }

    # ------------------------------------------------------------------ timeline
    def get_timeline(self) -> dict:
        s = self._load_summary()
        by_year = s.get("articles_by_year", {})
        by_month = s.get("articles_by_month", {})
        return {
            "available": bool(by_year),
            "date_range": s.get("date_range", {}),
            "by_year": [{"year": y, "count": c} for y, c in sorted(by_year.items())],
            "by_month": [{"month": m, "count": c} for m, c in sorted(by_month.items())],
            "note": "Based on historical HuffPost dataset publication dates.",
        }

    # ------------------------------------------------------------------ trends
    def get_trends(self) -> dict:
        s = self._load_summary()
        cby = s.get("category_by_year", {})
        if len(cby) < 2:
            return {"available": False,
                    "reason": "Insufficient date coverage for trend analysis",
                    "trends": []}

        years = sorted(cby.keys())
        recent = years[-2:] if len(years) >= 4 else years[-1:]
        earlier = years[-4:-2] if len(years) >= 4 else years[:-1]

        all_cats: set[str] = set()
        for y in years:
            all_cats.update(cby[y].keys())

        trends = []
        for cat in sorted(all_cats):
            rc = sum(cby.get(y, {}).get(cat, 0) for y in recent)
            ec = sum(cby.get(y, {}).get(cat, 0) for y in earlier)
            ra, ea = rc / max(len(recent), 1), ec / max(len(earlier), 1)
            pct = round((ra - ea) / ea * 100, 1) if ea > 0 else (100.0 if ra > 0 else 0.0)
            direction = "rising" if pct > 10 else ("declining" if pct < -10 else "stable")
            trends.append({"topic": cat, "recent_avg": round(ra, 1),
                           "earlier_avg": round(ea, 1), "change_percent": pct,
                           "direction": direction})

        trends.sort(key=lambda t: -abs(t["change_percent"]))
        return {
            "available": True,
            "method": "Year-over-year category frequency comparison in the historical dataset",
            "recent_period": recent,
            "earlier_period": earlier,
            "trends": trends[:25],
            "note": "These trends reflect changes in the historical HuffPost dataset, not live news.",
        }

    # ------------------------------------------------------------------ keywords
    def get_keywords(self, category: str | None = None, limit: int = 25) -> dict:
        key = f"{category or 'all'}_{limit}"
        if key in self._keyword_cache:
            return self._keyword_cache[key]

        if not self._dataset_path.exists():
            return {"available": False, "reason": "Dataset not found", "keywords": []}

        df = pd.read_csv(self._dataset_path, keep_default_na=False,
                         usecols=["category", "headline", "short_description"])
        if category:
            df = df[df["category"].str.upper() == category.upper()]
        if df.empty:
            return {"available": True, "keywords": [], "total_documents": 0}

        if len(df) > 30_000:
            df = df.sample(n=30_000, random_state=42)

        texts = (df["headline"].astype(str) + " " +
                 df["short_description"].astype(str)).str.strip()
        tfidf = TfidfVectorizer(max_features=3000, stop_words="english",
                                min_df=5, max_df=0.8, sublinear_tf=True)
        matrix = tfidf.fit_transform(texts)
        agg = np.asarray(matrix.sum(axis=0)).flatten()
        names = tfidf.get_feature_names_out()
        top = agg.argsort()[::-1][:limit]

        result = {
            "available": True,
            "category_filter": category,
            "total_documents": len(df),
            "method": "TF-IDF aggregate score across documents",
            "keywords": [{"term": str(names[i]), "tfidf_score": round(float(agg[i]), 2)}
                         for i in top],
        }
        self._keyword_cache[key] = result
        return result

    # --------------------------------------------- prediction-history analytics
    @staticmethod
    def get_prediction_stats(db_path: Path) -> dict:
        """Aggregate stats from the prediction_history table."""
        if not db_path.exists():
            return {"total_predictions": 0, "category_distribution": [],
                    "sentiment_distribution": [], "recent": [], "by_date": []}

        with closing(sqlite3.connect(db_path)) as conn:
            conn.row_factory = sqlite3.Row
            total = conn.execute("SELECT COUNT(*) FROM prediction_history").fetchone()[0]

            cats = conn.execute(
                "SELECT predicted_category, COUNT(*) AS cnt "
                "FROM prediction_history GROUP BY predicted_category ORDER BY cnt DESC"
            ).fetchall()

            sentiments = conn.execute(
                "SELECT sentiment_label, COUNT(*) AS cnt "
                "FROM prediction_history WHERE sentiment_label IS NOT NULL "
                "GROUP BY sentiment_label ORDER BY cnt DESC"
            ).fetchall()

            recent = conn.execute(
                "SELECT id, headline, predicted_category, sentiment_label, created_at "
                "FROM prediction_history ORDER BY created_at DESC LIMIT 10"
            ).fetchall()

            by_date = conn.execute(
                "SELECT DATE(created_at) AS day, COUNT(*) AS cnt "
                "FROM prediction_history GROUP BY day ORDER BY day"
            ).fetchall()

        return {
            "total_predictions": total,
            "category_distribution": [{"category": r["predicted_category"], "count": r["cnt"]}
                                      for r in cats],
            "sentiment_distribution": [{"sentiment": r["sentiment_label"], "count": r["cnt"]}
                                       for r in sentiments],
            "recent": [dict(r) for r in recent],
            "by_date": [{"date": r["day"], "count": r["cnt"]} for r in by_date],
        }
